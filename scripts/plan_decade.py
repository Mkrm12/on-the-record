"""Write the ten-year corpus plan: the gaps around the existing windows, as a config that EXTENDS the base."""

from __future__ import annotations

import argparse
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ingest import window_plan as WP  # noqa: E402
from ingest.corpus_fetch import load_config  # noqa: E402

BASE = ROOT / "config" / "corpus_v2.toml"
OUT = ROOT / "config" / "corpus_decade.toml"
# The maintainer's span: "we go from 2015".
DECADE_START = date(2015, 1, 1)


def main() -> int:
    yesterday = date.today() - timedelta(days=1)
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--start", type=date.fromisoformat, default=None,
                        help=f"first day of the span (default: {DECADE_START})")
    parser.add_argument("--end", type=date.fromisoformat, default=yesterday,
                        help="last day (default: yesterday — today's record may still be incomplete)")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    end = args.end
    start = args.start or DECADE_START
    if end > yesterday:
        raise SystemExit(f"--end {end} is not in the past; the record for it may be incomplete")

    base = load_config(BASE, repo_root=ROOT)
    existing = [w for w in base.windows if w.active]
    gaps = WP.gap_windows(existing, start, end)
    new_days = sum(len(w.days) for w in gaps)
    old_days = sum(len(w.days) for w in existing if start <= w.start and w.end <= end)
    print(f"span {start} .. {end}: {(end - start).days + 1:,} days")
    print(f"  existing active windows inside it: {len(existing)} ({old_days:,} days) — untouched")
    print(f"  corpus windows to add:             {len(gaps)} ({new_days:,} days), quarter-bounded")
    if gaps:
        print(f"  first {gaps[0].id} {gaps[0].start}..{gaps[0].end}   last {gaps[-1].id} {gaps[-1].start}..{gaps[-1].end}")
    # A rough volume from this corpus's own density.
    chunks_per_day = 1_437_856 / max(1, sum(len(w.days) for w in existing))
    print(f"  rough scale: ~{chunks_per_day * new_days / 1e6:.1f} M more chunks at this corpus's density "
          f"({chunks_per_day:,.0f} chunks per calendar day)")

    header = (f"The ten-year corpus extension, generated by scripts/plan_decade.py for {start} .. {end}.\n"
              "It EXTENDS corpus_v2.toml and only adds windows: the gaps around W0-W5, cut into calendar quarters,\n"
              "role `corpus` (loaded and searchable, never evaluated, no gold). Regenerate rather than hand-edit.")
    text = WP.to_toml(gaps, extends=BASE.name, header=header)
    if args.dry_run:
        print("\n(dry run: nothing written)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    # Prove it: the same validator the fetch and load tools use.
    check = load_config(OUT, repo_root=ROOT)
    assert len(check.windows) == len(base.windows) + len(gaps)
    print(f"\nwrote {OUT.relative_to(ROOT)} — {len(check.windows)} windows load and validate "
          f"({len(base.windows)} base + {len(gaps)} corpus)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
