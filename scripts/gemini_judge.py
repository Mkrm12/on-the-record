def _entry_fields(item: Any, row: dict) -> dict:
    """An entry without its id, in the bank's stored (v2) form: what a real answer and an instrument item share."""
    return {k: v for k, v in _entry("", item, row).items() if k != "id"}


def _required(item: Any) -> int:
    """`schema.vital_required`, for anything shaped like a gold item (the tests use plain namespaces)."""
    vital = sum(1 for n in (item.nuggets or ()) if getattr(n, "vital", False))
    k = getattr(item, "min_points", None)
    return min(k, vital) if getattr(item, "breadth", "") == "broad" and k is not None else vital


def _points_v3(item: Any) -> list[dict]:
    return [{"text": str(getattr(n, "text", n)), "vital": bool(getattr(n, "vital", False)),
             "kind": getattr(n, "kind", "") or "", "side": getattr(n, "side", "") or ""} for n in (item.nuggets or ())]


def _bank_entry(item: Any, row: dict) -> dict:
    """An instrument item's stored entry: what a real answer's entry is, kinds, sides and k of n included, so that a v3
    packet cannot tell it from an answer. `packet_entry` blanks them again for a v2 packet.
    """
    return {**_entry_fields(item, row), "reference_points": _points_v3(item), "vital_required": _required(item)}


def verdict_carries_over(old_vitals: list[str], new_vitals: list[str]) -> bool:
    """Whether an maintainer's verdict, given against `old_vitals`, still holds against `new_vitals`: the same number
    of vital points, each new one the old one or a cut of it (a citer removed). Anything else needs the maintainer
    again.
    """
    def norm(text: str) -> str:
        return " ".join(text.replace("\u2019", "'").split()).rstrip(".").casefold()

    return len(old_vitals) == len(new_vitals) and all(norm(n) in norm(o) for o, n in zip(old_vitals, new_vitals))


