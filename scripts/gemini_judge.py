def read_reply(path: Path) -> dict:
    """Gemini's reply, tolerating prose around it or a code fence: the outermost JSON object (or a bare array)."""
    text = Path(path).read_text(encoding="utf-8")
    fenced = re.search(r"```(?:json)?\s*(.*?)```", text, flags=re.S)
    if fenced:
        text = fenced.group(1)
    starts = [i for i in (text.find("{"), text.find("[")) if i >= 0]
    if not starts:
        raise ImportRefused("the reply holds no JSON")
    start = min(starts)
    end = text.rfind("}" if text[start] == "{" else "]")
    try:
        data = json.loads(text[start:end + 1])
    except json.JSONDecodeError as exc:
        raise ImportRefused(f"the reply is not valid JSON ({exc})") from exc
    return {"verdicts": data} if isinstance(data, list) else data


def check(reply: dict, key: dict, *, partial: bool = False, skip_counts: bool = False) -> list[str]:
    """Every reason the reply cannot be imported; empty when it can."""
    problems = []
    if reply.get("packet_id") and reply["packet_id"] != key["packet_id"]:
        problems.append(f"the reply names packet {reply['packet_id']!r}, not {key['packet_id']!r} — a reply to another "
                        "packet")
    elif not reply.get("packet_id"):
        problems.append("the reply does not name its packet_id, so it cannot be bound to this packet")
    verdicts = reply.get("verdicts")
    if not isinstance(verdicts, list):
        return problems + ["the reply has no list of verdicts"]
    seen = Counter(str(v.get("id")) for v in verdicts if isinstance(v, dict))
    problems += [f"{jid} is graded more than once" for jid, n in seen.items() if n > 1]
    problems += [f"{jid} is an unknown id (not in this packet)" for jid in seen if jid not in key["map"]]
    if not partial:
        absent = sorted(set(key["map"]) - set(seen))
        if absent:
            problems.append(f"{len(absent)} id(s) missing from the reply: {absent[:12]}")
    for v in verdicts:
        if not isinstance(v, dict):
            problems.append(f"a verdict is not an object: {str(v)[:60]}")
            continue
        jid = str(v.get("id"))
        if jid not in key["map"]:
            continue
        outcome = v.get("outcome")
        if outcome not in OUTCOMES:
            problems.append(f"{jid}: outcome {outcome!r} is not one of {OUTCOMES}")
            continue
        total, present = v.get("vital_total"), v.get("vital_present")
        if total != key["vital_totals"][jid]:
            problems.append(f"{jid}: vital_total {total!r} disagrees with the packet's {key['vital_totals'][jid]}")
            continue
        if not isinstance(present, int) or isinstance(present, bool) or not 0 <= present <= total:
            problems.append(f"{jid}: vital_present {present!r} is not a count from 0 to {total}")
            continue
        if not skip_counts and outcome in ("correct", "correct_missing_okay_nuggets") and present < total:
            problems.append(f"{jid}: {outcome!r} contradicts its own count ({present} of {total} vital points)")
        if not skip_counts and outcome == "missing_vital_nugget" and present >= total:
            problems.append(f"{jid}: 'missing_vital_nugget' contradicts its own count ({present} of {total} vital "
                            "points present)")
        if not str(v.get("why") or "").strip():
            problems.append(f"{jid}: no why — a verdict without its reason cannot be calibrated or checked")
    return problems


ANSWERED_RIGHT = ("correct", "correct_missing_okay_nuggets")


def points_problems(jid: str, verdict: dict, meta: dict) -> list[str]:
    """Rubric v3: the verdict's own list of points, checked against what its entry needs."""
    points, required = meta["points"], meta["required"]
    listed = verdict.get("points_present")
    if (not isinstance(listed, list) or len(set(map(str, listed))) != len(listed)
            or not all(isinstance(n, int) and not isinstance(n, bool) and 1 <= n <= len(points) for n in listed)):
        return [f"{jid}: points_present must list the numbers (1 to {len(points)}) of the reference points the answer "
                "states, each once"]
    vital = [n for n in listed if points[n - 1][0]]
    problems = []
    if verdict.get("vital_present") != len(vital):
        problems.append(f"{jid}: vital_present {verdict.get('vital_present')!r} disagrees with the {len(vital)} VITAL "
                        "point(s) its points_present lists")
    sides = {side for is_vital, side, _ in points if is_vital and side}
    covered = {points[n - 1][1] for n in vital if points[n - 1][1]}
    met = len(vital) >= required and sides <= covered
    need = f"{required} VITAL point(s)" + (" and one from each side" if sides else "")
    if verdict.get("outcome") in ANSWERED_RIGHT and not met:
        problems.append(f"{jid}: {verdict['outcome']!r} needs {need}; the points listed give {len(vital)}"
                        + (f", missing the side(s) {sorted(sides - covered)}" if sides - covered else ""))
    if verdict.get("outcome") == "missing_vital_nugget" and met:
        problems.append(f"{jid}: 'missing_vital_nugget' contradicts its own list, which meets the entry's {need}")
    return problems


def judged_path(report_path: Path) -> Path:
    return report_path.with_name(f"{report_path.stem}_judged.json")


def read_replies(paths: list[Path]) -> dict:
    """One reply from one or more parts: the verdict lists joined, the packet named once."""
    parts = [read_reply(p) for p in paths]
    packets = {str(part.get("packet_id")) for part in parts if part.get("packet_id")}
    if len(packets) > 1:
        raise ImportRefused(f"the parts name different packets ({sorted(packets)}): they are not one reply")
    verdicts: list = []
    for part in parts:
        if not isinstance(part.get("verdicts"), list):
            raise ImportRefused("a part has no list of verdicts")
        verdicts += part["verdicts"]
    first = parts[0]
    return {**first, "packet_id": next(iter(packets), None), "verdicts": verdicts}


MODES = ("chat", "deep_research")


def import_verdicts(report_path: Path, verdicts_path: Path | list[Path], *, key_path: Path | None = None,
                    partial: bool = False, judge_name: str = JUDGE_NAME, out: Path | None = None,
                    judge_model: str | None = None, mode: str | None = None) -> Path:
    report_path = Path(report_path)
    key_path = Path(key_path) if key_path else OUT_DIR / f"key_{_stem(report_path)}.json"
    key = json.loads(key_path.read_text(encoding="utf-8"))
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if key.get("report") != report_path.name:
        raise ImportRefused(f"the key was made for {key.get('report')!r}, not {report_path.name!r}")
    paths = [Path(p) for p in verdicts_path] if isinstance(verdicts_path, (list, tuple)) else [Path(verdicts_path)]
    if key.get("version") == 2:
        return _import_v2(report_path, report, paths, key, key_path, partial=partial, judge_name=judge_name, out=out,
                          judge_model=judge_model, mode=mode)
    reply = read_replies(paths)
    problems = check(reply, key, partial=partial)
    if problems:
        raise ImportRefused(f"{len(problems)} problem(s); nothing was written:\n  " + "\n  ".join(problems))
    rows = {r["id"]: r for r in report["rows"]}
    disagreements = []
    for v in reply["verdicts"]:
        row = rows[key["map"][str(v["id"])]]
        if row.get("outcome") and row.get("by") not in AWAITING:
            if v["outcome"] != row["outcome"]:  # a deterministic grade stands; the disagreement is reported
                disagreements.append({"id": row["id"], "deterministic": row["outcome"], "gemini": v["outcome"],
                                      "why": str(v.get("why"))[:300]})
            continue
        row.update({"outcome": v["outcome"], "why": str(v.get("why"))[:300], "by": judge_name,
                    "vital_present": v["vital_present"], "vital_total": v["vital_total"],
                    "judge_confidence": v.get("confidence"), "judge_evidence": str(v.get("evidence") or "")[:300]})
    report.update(EA.outcome_fields(report["rows"]))
    model = str(reply.get("judge_model") or "unstated")
    report.update({"judge": f"{judge_name}/{model}", "judge_family": "gemini", "gate_evaluated": True,
                   "judged_offline": {"verdicts": [path.name for path in paths], "key": key_path.name,
                                      "packet_id": key["packet_id"], "imported_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                                      "partial": partial, "disagreements_with_deterministic": disagreements}})
    target = Path(out) if out else judged_path(report_path)
    target.write_text(json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8")
    return target


def _import_v2(report_path: Path, report: dict, paths: list[Path], key: dict, key_path: Path, *, partial: bool,
               judge_name: str, out: Path | None, judge_model: str | None, mode: str | None) -> Path:
    """Protocol v2: every packet's reply checked and guarded, its instrument scored, and only the packets whose
    instrument says the chat held steady merged. The maintainer names the model and the mode; the reply's claim is
    kept apart and never used.
    """
    if not (judge_model or "").strip():
        raise ImportRefused("name the model that graded these packets with --judge-model, as the Gemini app shows it; "
                            "the reply's own claim is never used (D-022)")
    if mode == "deep_research":
        raise ImportRefused("Deep Research searches the web, so its verdicts were not graded against the packet alone "
                            "(rubric rule 1; D-057). Grade the packets again in a normal chat with thinking on, and "
                            "import them with --mode chat")
    if mode != "chat":
        raise ImportRefused("say how the packets were graded with --mode chat (a normal Gemini chat, thinking on)")
    by_packet: dict[str, list] = {}
    claimed: set[str] = set()
    for path in paths:
        reply = read_reply(path)
        pid = str(reply.get("packet_id") or "")
        if not pid:
            raise ImportRefused(f"{path.name} does not name its packet_id, so it cannot be bound to a packet")
        if pid not in key["packets"]:
            raise ImportRefused(f"{path.name} names packet {pid!r}, which is not one of this run's packets")
        if not isinstance(reply.get("verdicts"), list):
            raise ImportRefused(f"{path.name} has no list of verdicts")
        by_packet.setdefault(pid, []).extend(reply["verdicts"])
        if reply.get("judge_model"):
            claimed.add(str(reply["judge_model"]))
    missing = [pid for pid in key["packets"] if pid not in by_packet]
    if missing and not partial:
        raise ImportRefused(f"{len(missing)} packet(s) not graded: "
                            + ", ".join(f"{key['packets'][p]['file']} ({p})" for p in missing)
                            + ". Import every packet, or use --partial on purpose (the gate then says INCOMPLETE)")
    problems = []
    for pid, verdicts in by_packet.items():
        k = key["packets"][pid]
        label = f"packet p{k['index']:02d}"
        view = {"packet_id": pid, "map": {**k["map"], **{jid: jid for jid in k["instrument"]}},
                "vital_totals": k["vital_totals"]}
        problems += [f"{label}: {p}" for p in check({"packet_id": pid, "verdicts": verdicts}, view, partial=partial,
                                                    skip_counts=True)]
        for v in verdicts:
            if isinstance(v, dict) and str(v.get("id")) in k["answers"]:
                jid = str(v["id"])
                problems += [f"{label}: {p}" for p in I.guard_problems(jid, v, k["answers"][jid], k["declines"][jid])]
                if v.get("outcome") in OUTCOMES:
                    problems += [f"{label}: {p}" for p in points_problems(jid, v, k["points"][jid])]
    if problems:
        raise ImportRefused(f"{len(problems)} problem(s); nothing was written:\n  " + "\n  ".join(problems))
    rows = {r["id"]: r for r in report["rows"]}
    scores, disagreements = {}, []
    for pid, verdicts in by_packet.items():
        k = key["packets"][pid]
        by_id = {str(v["id"]): v for v in verdicts}
        scores[pid] = I.score_packet(k["instrument"], by_id)
        if k.get("resample"):
            continue  # the stability resample: compared below, never merged
        if scores[pid]["provisional"]:
            continue  # graded again in a fresh chat; nothing of this packet is merged
        for jid, item_id in k["map"].items():
            v = by_id.get(jid)
            if v is None:
                continue
            row = rows[item_id]
            if row.get("outcome") and row.get("by") not in AWAITING:
                if v["outcome"] != row["outcome"]:
                    disagreements.append({"id": row["id"], "deterministic": row["outcome"], "gemini": v["outcome"],
                                          "why": str(v.get("why"))[:300]})
                continue
            row.update({"outcome": v["outcome"], "why": str(v.get("why"))[:300], "by": judge_name,
                        "vital_present": v["vital_present"], "vital_total": v["vital_total"],
                        "judge_confidence": v.get("confidence"), "judge_evidence": str(v.get("evidence") or "")[:300],
                        "judge_packet": pid, "vital_required": k["points"][jid]["required"],
                        "points_present": v.get("points_present")})
    report.update(EA.outcome_fields(report["rows"]))
    own = {pid: score for pid, score in scores.items() if not key["packets"][pid].get("resample")}
    report.update({"judge": f"{judge_name}/{judge_model.strip()}", "judge_family": "gemini", "judge_mode": mode,
                   "gate_evaluated": True, "instrument": I.summarise(own), "rubric": key.get("rubric"),
                   "judge_stability": stability(key, by_packet, scores, rows, judge_name),
                   "judged_offline": {"protocol": 2, "verdicts": [p.name for p in paths], "key": key_path.name,
                                      "packets_graded": sorted(by_packet), "packets_missing": missing,
                                      "imported_at": time.strftime("%Y-%m-%dT%H:%M:%S"), "partial": partial,
                                      "judge_model_claimed": sorted(claimed),
                                      "disagreements_with_deterministic": disagreements}})
    target = Path(out) if out else judged_path(report_path)
    target.write_text(json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8")
    return target


def stability(key: dict, by_packet: dict[str, list], scores: dict[str, dict], rows: dict[str, dict],
              judge_name: str) -> dict[str, Any]:
    """The resample's verdicts against the first ones, answer by answer: how often the judge flipped on identical
    input.
    """
    resample = {pid: k for pid, k in key["packets"].items() if k.get("resample")}
    if not resample:
        return {"status": "not measured: this export made no resample packet"}
    skipped = [pid for pid in resample if pid not in by_packet or scores.get(pid, {}).get("provisional")]
    pairs: list[tuple[str, str, str]] = []
    for pid, k in resample.items():
        if pid in skipped:
            continue
        by_id = {str(v["id"]): v for v in by_packet[pid]}
        for jid, item_id in k["map"].items():
            v, row = by_id.get(jid), rows.get(item_id) or {}
            if v is None or row.get("by") != judge_name or v.get("outcome") not in OUTCOMES:
                continue
            pairs.append((item_id, row["outcome"], v["outcome"]))
    if not pairs:
        why = "its packets were not graded or their instrument drifted" if skipped else "no verdict to compare"
        return {"status": f"not measured: {why}", "skipped_packets": skipped}
    flips = [p for p in pairs if p[1] != p[2]]
    harmful = [p for p in pairs if (p[1] == "harmful") != (p[2] == "harmful")]
    return {"status": "measured", "share": key.get("resample_share"), "compared": len(pairs), "flips": len(flips),
            "flip_rate": round(len(flips) / len(pairs), 4), "flip_wilson_95": I.wilson(len(flips), len(pairs)),
            "harmful_disagreements": len(harmful), "flipped": sorted(p[0] for p in flips),
            "pairs": dict(Counter(f"{a} -> {b}" for _, a, b in flips)), "skipped_packets": skipped}  # fmt: skip


# --- compare --------------------------------------------------------------------------------------------------------


def compare(a: dict, b: dict) -> dict[str, Any]:
    """Two Gemini passes over one packet, verdict by verdict."""
    if a.get("packet_id") != b.get("packet_id"):
        raise ImportRefused("the two replies grade different packets")
    first = {str(v["id"]): v["outcome"] for v in a["verdicts"]}
    second = {str(v["id"]): v["outcome"] for v in b["verdicts"]}
    common = sorted(set(first) & set(second))
    flips = [jid for jid in common if first[jid] != second[jid]]
    harmful = [jid for jid in common if (first[jid] == "harmful") != (second[jid] == "harmful")]
    return {"compared": len(common), "flips": len(flips), "flip_rate": round(len(flips) / len(common), 4) if common
            else None, "harmful_disagreements": len(harmful), "flipped": flips,
            "pairs": dict(Counter(f"{first[j]} -> {second[j]}" for j in flips))}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="command", required=True)
    ex = sub.add_parser("export", help="the blind packets for Gemini (protocol v2), and their key")
    ex.add_argument("--report", required=True, type=Path)
    ex.add_argument("--all", action="store_true",
                    help="also the deterministically graded answers, as a cross-check (they are never overwritten)")
    ex.add_argument("--max-items", type=int, default=I.MAX_ITEMS, help="answers per packet (one fresh chat each)")
    ex.add_argument("--sentinels", type=int, default=I.SENTINELS_PER_PACKET)
    ex.add_argument("--seeds", type=int, default=I.SEEDS_PER_PACKET)
    ex.add_argument("--canaries", type=int, default=I.CANARIES_PER_PACKET)
    ex.add_argument("--bank", type=Path, default=I.BANK_PATH)
    ex.add_argument("--rubric", choices=("v2", "v3"), default=R.RUBRIC_VERSION,
                    help="v3 (default): k of n for broad items, examples never required; v2: every vital point needed")
    ex.add_argument("--legacy", action="store_true",
                    help="the old single packet with no instrument (only to reproduce a run judged before protocol v2)")
    im = sub.add_parser("import", help="Gemini's verdicts, checked, guarded, merged and scored")
    im.add_argument("--report", required=True, type=Path)
    im.add_argument("--verdicts", required=True, type=Path, nargs="+",
                    help="every packet's reply (several files per packet when Gemini answered in parts)")
    im.add_argument("--key", type=Path, default=None)
    im.add_argument("--partial", action="store_true", help="import the valid verdicts and leave the rest ungraded")
    im.add_argument("--judge-model", default=None, help="the model that graded, as the Gemini app names it")
    im.add_argument("--mode", choices=MODES, default=None, help="how it graded: chat (Deep Research is refused)")
    bk = sub.add_parser("bank", help="build the instrument's bank from the owner's triage and the dev s18 run")
    bk.add_argument("--out", type=Path, default=I.BANK_PATH)
    cp = sub.add_parser("compare", help="two Gemini passes over the same packet")
    cp.add_argument("a", type=Path)
    cp.add_argument("b", type=Path)
    pr = sub.add_parser("prompt", help="print the judging prompt (the rubric's); --write puts it at the foot of "
                                       "logs/GEMINI_LOG.md")
    pr.add_argument("--write", action="store_true")
    args = p.parse_args(argv)
    if args.command == "prompt":
        if args.write:
            changed = write_prompt()
            print(f"logs/GEMINI_LOG.md: the prompt is {'written' if changed else 'already current'}")
        else:
            sys.stdout.reconfigure(encoding="utf-8")  # £, — and … intact in any console, or when piped to a file
            print(R.judging_prompt())
        return 0
    if args.command == "bank":
        bank = build_bank()
        args.out.write_text(json.dumps(bank, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {args.out.relative_to(ROOT)}: {len(bank['sentinels'])} sentinels (the owner's verdicts), "
              f"{len(bank['seed_bases'])} seed bases, {len(bank['excluded'])} held back (the sealed window, or awaiting "
              "the owner's re-adjudication)")
        return 0
    if args.command == "export" and not args.legacy:
        paths = export_v2(args.report, bank=I.load_bank(args.bank), max_items=args.max_items,
                          sentinels=args.sentinels, seeds=args.seeds, canaries=args.canaries, include_graded=args.all,
                          rubric=args.rubric)
        key = json.loads(Path(paths["key"]).read_text(encoding="utf-8"))
        real = sum(len(k["map"]) for k in key["packets"].values() if not k.get("resample"))
        again = sum(1 for k in key["packets"].values() if k.get("resample"))
        print(f"the stability resample: {len(key['resampled'])} of them again in {again} packet(s) of their own; "
              f"grade those in fresh chats too (their verdicts are compared, never merged)")
        print(f"{real} answers to grade in {len(key['packets'])} packet(s) of at most {args.max_items}, each with "
              f"{args.sentinels} sentinels, {args.seeds} seeded harms and {args.canaries} canary hidden among them")
        for warning in key["shortfall"]:
            print(f"WARNING: {warning}")
        for p in paths["packets"]:
            print(f"  packet   {Path(p).relative_to(ROOT)}")
        print(f"  key      {Path(paths['key']).relative_to(ROOT)}  (never give it to Gemini)")
        print("Grade each packet in its own NEW chat (normal chat, thinking on; never Deep Research) with the prompt at "
              "the foot of logs/GEMINI_LOG.md. Save each reply as reports/gemini/reply_<run>_pNN.json.")
        return 0
    if args.command == "export":
        paths = export(args.report, include_graded=args.all)
        packet = json.loads(Path(paths["packet"]).read_text(encoding="utf-8"))
        print(f"{packet['answers_to_grade']} answers to grade, packet {packet['packet_id']}")
        failed = [r["id"] for r in json.loads(Path(args.report).read_text(encoding="utf-8"))["rows"]
                  if r.get("by") == EA.FAILED]  # fmt: skip
        if failed:
            print(f"WARNING: {len(failed)} request(s) FAILED in this run and have no answer to grade ({failed[:8]}). "
                  "Re-run them first (eval_answers.py ... --resume), or the judged gate stays INCOMPLETE.")
        for name, path in paths.items():
            print(f"  {name:8s} {Path(path).relative_to(ROOT)}")
        print("Give Gemini the prompt at the foot of logs/GEMINI_LOG.md and the packet (.json or .md). Never the key.")
        return 0
    if args.command == "import":
        try:
            target = import_verdicts(args.report, args.verdicts, key_path=args.key, partial=args.partial,
                                     judge_model=args.judge_model, mode=args.mode)
        except ImportRefused as exc:
            print(f"REFUSED: {exc}")
            return 1
        judged = json.loads(target.read_text(encoding="utf-8"))
        print(f"wrote {target.relative_to(ROOT)}: graded {judged['graded']} of {judged['items']}, "
              f"ungraded {judged['ungraded']}; outcomes {judged['by_outcome']}")
        inst = judged.get("instrument")
        if inst:
            seeded = inst["seeded_harm"]
            print(f"instrument: {inst['status'].upper()}; seeded harms caught {seeded['caught']}/{seeded['n']}"
                  f" (95% {seeded['wilson_95']}); sentinels right {inst['sentinels']['right']}/{inst['sentinels']['n']};"
                  f" canaries clean {inst['canaries']['clean']}/{inst['canaries']['n']}")
            for reason in inst["reasons"]:
                print(f"  - {reason}")
        disagree = judged["judged_offline"]["disagreements_with_deterministic"]
        if disagree:
            print(f"Gemini disagrees with {len(disagree)} deterministic grade(s) (they stand): "
                  f"{[d['id'] for d in disagree][:12]}")
        print(f"next: uv run python scripts/e3_gate_report.py {target.relative_to(ROOT)}")
        return EA.exit_code(judged)
    result = compare(read_reply(args.a), read_reply(args.b))
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
