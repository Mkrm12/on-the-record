def _entry_v3(item: Any, row: dict, rubric: str) -> dict:
    """A packet entry under `rubric`: v3 says what each point is and how many a right answer needs; v2 needs them all.
    """
    entry = _entry_fields(item, row)
    if rubric == "v3":
        entry["reference_points"] = _points_v3(item)
        entry["vital_required"] = _required(item)
    return I.packet_entry(entry, rubric)


# The share of a run's answers graded a second time, in packets of their own.
RESAMPLE_SHARE = 0.10


def export_v2(report_path: Path, out_dir: Path = OUT_DIR, *, bank: dict | None = None, max_items: int = I.MAX_ITEMS,
              sentinels: int = I.SENTINELS_PER_PACKET, seeds: int = I.SEEDS_PER_PACKET,
              canaries: int = I.CANARIES_PER_PACKET, include_graded: bool = False,
              rubric: str = R.RUBRIC_VERSION, resample: float = RESAMPLE_SHARE) -> dict[str, Any]:
    """Packets of at most `max_items` answers, each graded in a fresh chat, each hiding its instrument items."""
    report_path = Path(report_path)
    report = json.loads(report_path.read_text(encoding="utf-8"))
    gold = load_gold_map()
    bank = I.load_bank() if bank is None else bank
    problems = I.bank_problems(bank)
    if problems:
        raise SystemExit("the judge bank cannot be used:\n  " + "\n  ".join(problems[:20]))
    rows = [r for r in report["rows"] if r.get("by") != "gold-incomplete"
            and (include_graded or (not r.get("outcome") and r.get("by") in AWAITING))]  # fmt: skip
    if not rows:
        raise SystemExit(f"{report_path.name}: no answer is waiting for a judge (nothing to export)")
    missing = sorted(r["id"] for r in rows if r["id"] not in gold)
    if missing:
        raise SystemExit(f"rows with no gold item: {missing[:10]}")
    # E3's retrieval was never masked, so a stored answer can quote a speech from the sealed W5 window.
    held_back = sorted(r["id"] for r in rows if I.mentions_sealed_window(_entry_fields(gold[r["id"]], r)))
    rows = [r for r in rows if r["id"] not in held_back]
    if not rows:
        raise SystemExit(f"{report_path.name}: every answer waiting for a judge cites the sealed window")
    run_id = str(report.get("run_id", ""))
    order = list(rows)
    random.Random(f"{run_id}|gemini").shuffle(order)
    run_items = {r["id"] for r in rows}  # only what is being graded: no question may appear twice in one packet set
    stem = _stem(report_path)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, list[str]] = {"packets": [], "markdown": []}
    packets: dict[str, dict] = {}
    shortfall: list[str] = []
    batches = [(index, order[start:start + max_items], f"{run_id}|v2|{index}", f"p{index:02d}", False)
               for index, start in enumerate(range(0, len(order), max_items), start=1)]
    again: list[dict] = []
    if resample > 0 and order:
        again = random.Random(f"{run_id}|resample").sample(order, max(1, math.ceil(resample * len(order))))
        first = len(batches)
        batches += [(first + n, again[start:start + max_items], f"{run_id}|v2|resample|{n}", f"r{n:02d}", True)
                    for n, start in enumerate(range(0, len(again), max_items), start=1)]  # fmt: skip
    for index, batch, seed_label, suffix, is_resample in batches:
        rng = random.Random(seed_label)
        chosen, short = I.choose(bank, exclude=run_items, rng=rng, label=f"packet {suffix}", sentinels=sentinels,
                                 seeds=seeds, canaries=canaries, rubric=rubric)
        shortfall += short
        mixed = [(_entry_v3(gold[r["id"]], r, rubric), r["id"]) for r in batch]
        mixed += [(I.packet_entry(entry, rubric), meta) for entry, meta in chosen]
        rng.shuffle(mixed)
        entries, mapping, instrument, vital_totals, answers, declines, points = [], {}, {}, {}, {}, {}, {}
        for n, (entry, what) in enumerate(mixed, start=1):
            jid = f"J{n:03d}"
            entries.append({"id": jid, **entry})
            if isinstance(what, str):
                mapping[jid] = what
            else:
                instrument[jid] = what
            vital_totals[jid], answers[jid], declines[jid] = (entry["vital_total"], entry["answer"],
                                                              entry["answer_is_a_decline"])
            points[jid] = {"points": [[p["vital"], p["side"], p["kind"]] for p in entry["reference_points"]],
                           "required": entry["vital_required"]}
        canonical = json.dumps(entries, sort_keys=True, ensure_ascii=False)
        packet_id = hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:16]
        packet = {"packet_id": packet_id, "split": report.get("split"), "answers_to_grade": len(entries),
                  "instructions": "Grade every entry with the prompt you were given; reply with JSON only.",
                  "entries": entries}
        name = f"packet_{stem}_{suffix}"
        (out_dir / f"{name}.json").write_text(json.dumps(packet, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        (out_dir / f"{name}.md").write_text(markdown(packet), encoding="utf-8")
        written["packets"].append(str(out_dir / f"{name}.json"))
        written["markdown"].append(str(out_dir / f"{name}.md"))
        packets[packet_id] = {"index": index, "file": f"{name}.json", "map": mapping, "instrument": instrument,
                              "points": points, "resample": is_resample,
                              "vital_totals": vital_totals, "answers": answers, "declines": declines}
    key = {"version": 2, "report": report_path.name, "run_id": report.get("run_id"),
           "created": time.strftime("%Y-%m-%dT%H:%M:%S"), "include_graded": include_graded,
           "rubric": rubric, "bank_rubric": bank.get("rubric"), "max_items": max_items,
           "plan": {"sentinels": sentinels, "seeds": seeds, "canaries": canaries}, "shortfall": shortfall,
           "resample_share": resample, "resampled": sorted(r["id"] for r in again),
           "held_back_sealed": held_back, "packets": packets}
    key_path = out_dir / f"key_{stem}.json"
    key_path.write_text(json.dumps(key, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return {**written, "key": str(key_path)}


def build_bank(triage_key: Path = ROOT / "reports" / "triage_key.json",
               triage_labels: Path = ROOT / "reports" / "triage_labels.json",
               report_path: Path = ROOT / "reports" / "e3_eval_dev_s18_final_judged.json",
               rewritten: Path | None = REWRITTEN) -> dict:
    """The instrument's bank: the maintainer's adjudicated triage cards as sentinels, and the run's deterministically
    correct structured answers (the facts SQL proved) as the bases of seeded harms. Nothing dated inside the sealed
    window, and no sentinel whose vital points were rewritten after the maintainer judged it
    (`verdict_carries_over`).
    """
    gold = load_gold_map()
    before = {}
    if rewritten and Path(rewritten).exists():
        before = json.loads(Path(rewritten).read_text(encoding="utf-8"))["items"]
    cards = json.loads(Path(triage_key).read_text(encoding="utf-8"))["cards"]
    labels = json.loads(Path(triage_labels).read_text(encoding="utf-8"))["cards"]
    rows = {r["id"]: r for r in json.loads(Path(report_path).read_text(encoding="utf-8"))["rows"]}
    sentinels, bases, excluded = [], [], []
    for jid, card in cards.items():
        final = (labels.get(jid) or {}).get("final")
        if not final:
            continue
        item = gold[card["item_id"]]
        entry = _bank_entry(item, rows[card["item_id"]])
        source = f"triage:{jid}"
        if I.mentions_sealed_window(entry):
            excluded.append({"source": source, "reason": "names a date inside the sealed W5 window"})
            continue
        old = before.get(card["item_id"])
        present = labels[jid].get("final_vital")
        if old and not verdict_carries_over([n["text"] for n in old["nuggets"] if n["vital"]],
                                            [n.text for n in item.nuggets if n.vital]):
            if not labels[jid].get("final_v3"):
                excluded.append({"source": source, "reason": "its vital points were rewritten after the owner's "
                                                             "verdict (gold v3, 2026-10-10): the owner must "
                                                             "re-adjudicate it (final_v3)"})
                continue
            # the maintainer's verdict against the rewritten points; the v2 one stays on record for E3's adjudication
            final, present = labels[jid]["final_v3"], labels[jid].get("final_vital_v3")
        if present is None:
            present = entry["vital_total"] if I.CLASS[final] == "right" else 0
        sentinels.append({"source": source, "item": card["item_id"], "breadth": getattr(gold[card["item_id"]],
                                                                                         "breadth", ""),
                          "known_outcome": final, "known_vital_present": int(present), "entry": entry})
    for row in rows.values():
        if row.get("by") != "deterministic-structured" or row.get("outcome") != "correct":
            continue
        entry = _bank_entry(gold[row["id"]], row)
        if I.mentions_sealed_window(entry):
            excluded.append({"source": f"dev_s18:{row['id']}", "reason": "names a date inside the sealed W5 window"})
            continue
        kinds = [k for k in perturbable_kinds(entry["answer"], [p["text"] for p in entry["reference_points"]],
                                              entry["must_not_claim"]) if k in JUDGE_SAFE]  # fmt: skip
        if kinds:
            bases.append({"source": f"dev_s18:{row['id']}", "item": row["id"], "kinds": kinds, "entry": entry})
    bank = {"version": 1, "rubric": "v2", "entries": "v3 (kinds, sides, vital_required)",
            "built": time.strftime("%Y-%m-%d"),
            "from": {"sentinels": f"{Path(triage_key).name} + {Path(triage_labels).name} (the owner's final verdicts)",
                     "seed_bases": f"{Path(report_path).name} (deterministic-structured, correct)"},
            "sentinels": sentinels, "seed_bases": bases, "excluded": excluded}
    problems = I.bank_problems(bank)
    if problems:
        raise SystemExit("the bank built from the triage is unusable:\n  " + "\n  ".join(problems[:20]))
    return bank


def _tags(point: dict) -> str:
    """A reference point's kind and side, as the markdown packet shows them ("example" says it is never required).
    """
    tags = []
    if point.get("kind") == "example":
        tags.append("example, never required")
    elif point.get("kind"):
        tags.append(point["kind"])
    if point.get("side"):
        tags.append(f"side: {point['side']}")
    return f" ({'; '.join(tags)})" if tags else ""


def markdown(packet: dict) -> str:
    lines = [f"# Answers to grade — packet {packet['packet_id']}", "",
             f"{packet['answers_to_grade']} answers. Grade each with the prompt you were given. Reply with JSON only, "
             f'and copy this packet_id into it: "{packet["packet_id"]}".', ""]
    for e in packet["entries"]:
        needs = (f"; this entry needs {e['vital_required']} of the {e['vital_total']} VITAL points"
                 if "vital_required" in e else "")
        lines += [f"## {e['id']}", "", f"**Question:** {e['question']}", "", f"**A right response:** {e['expected']}",
                  "", f"**Reference points** (vital_total = {e['vital_total']}{needs}):"]
        lines += [f"{n}. [{'VITAL' if p['vital'] else 'optional'}]{_tags(p)} {p['text']}"
                  for n, p in enumerate(e["reference_points"], start=1)] or ["- (none)"]
        lines += ["", "**Must not claim:**"] + ([f"- {c}" for c in e["must_not_claim"]] or ["- (nothing listed)"])
        lines += ["", "**The answer" + (" (a decline)" if e["answer_is_a_decline"] else "") + ":**", ""]
        lines += [f"> {line}" if line else ">" for line in e["answer"].splitlines()] + ["", "---", ""]
    return "\n".join(lines)


